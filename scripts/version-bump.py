#!/usr/bin/env python3
"""
Auto-version bump script for Series Radar.
Usage: python scripts/version-bump.py [major|minor|patch]
"""
import re
import sys
import subprocess
from pathlib import Path

def get_current_version():
    """Read current version from web/package.json and android-native/app/build.gradle.kts"""
    # Read from package.json
    pkg_path = Path("web/package.json")
    pkg_content = pkg_path.read_text()
    pkg_match = re.search(r'"version":\s*"(\d+\.\d+\.\d+)"', pkg_content)
    if not pkg_match:
        raise ValueError("Could not find version in web/package.json")
    web_version = pkg_match.group(1)

    # Read from build.gradle.kts
    gradle_path = Path("android-native/app/build.gradle.kts")
    gradle_content = gradle_path.read_text()
    version_code_match = re.search(r'versionCode\s*=\s*(\d+)', gradle_content)
    version_name_match = re.search(r'versionName\s*=\s*"(\d+\.\d+\.\d+)"', gradle_content)
    if not version_code_match or not version_name_match:
        raise ValueError("Could not find version in android-native/app/build.gradle.kts")
    version_code = int(version_code_match.group(1))
    gradle_version = version_name_match.group(1)

    if web_version != gradle_version:
        raise ValueError(f"Version mismatch: web={web_version}, android={gradle_version}")

    return web_version, version_code

def bump_version(version: str, bump_type: str) -> str:
    """Bump version string (major|minor|patch)"""
    major, minor, patch = map(int, version.split("."))
    if bump_type == "major":
        major += 1
        minor = 0
        patch = 0
    elif bump_type == "minor":
        minor += 1
        patch = 0
    elif bump_type == "patch":
        patch += 1
    else:
        raise ValueError(f"Invalid bump type: {bump_type}")
    return f"{major}.{minor}.{patch}"

def update_package_json(new_version: str):
    """Update web/package.json"""
    pkg_path = Path("web/package.json")
    content = pkg_path.read_text()
    content = re.sub(r'"version":\s*"\d+\.\d+\.\d+"', f'"version": "{new_version}"', content)
    pkg_path.write_text(content)

def update_build_gradle(new_version: str, new_version_code: int):
    """Update android-native/app/build.gradle.kts"""
    gradle_path = Path("android-native/app/build.gradle.kts")
    content = gradle_path.read_text()
    content = re.sub(r'versionCode\s*=\s*\d+', f'versionCode = {new_version_code}', content)
    content = re.sub(r'versionName\s*=\s*"\d+\.\d+\.\d+"', f'versionName = "{new_version}"', content)
    gradle_path.write_text(content)

def update_web_manifest_version(new_version: str):
    """Update PWA manifest version in web/index.html or manifest"""
    # The manifest is generated by vite-plugin-pwa, version comes from package.json
    pass

def git_commit_and_tag(new_version: str, new_version_code: int):
    """Commit changes and create git tag"""
    subprocess.run(["git", "add", "web/package.json", "android-native/app/build.gradle.kts"], check=True)
    subprocess.run(["git", "commit", "-m", f"chore: release v{new_version}"], check=True)
    subprocess.run(["git", "tag", "-a", f"v{new_version}", "-m", f"Release v{new_version}"], check=True)

def generate_changelog(new_version: str) -> str:
    """Generate changelog from git commits since last tag"""
    try:
        # Get last tag
        result = subprocess.run(["git", "describe", "--tags", "--abbrev=0"], capture_output=True, text=True, check=True)
        last_tag = result.stdout.strip()
    except subprocess.CalledProcessError:
        last_tag = ""

    if last_tag:
        cmd = ["git", "log", f"{last_tag}..HEAD", "--pretty=format:- %s (%h)", "--no-merges"]
    else:
        cmd = ["git", "log", "--pretty=format:- %s (%h)", "--no-merges"]

    result = subprocess.run(cmd, capture_output=True, text=True, check=True)
    commits = result.stdout.strip().split("\n")
    changelog = f"## v{new_version}\n\n"
    changelog += "\n".join(commits) if commits else "No changes"
    return changelog

def main():
    if len(sys.argv) < 2:
        print("Usage: python scripts/version-bump.py [major|minor|patch]")
        sys.exit(1)

    bump_type = sys.argv[1].lower()
    if bump_type not in ("major", "minor", "patch"):
        print("Invalid bump type. Use: major, minor, or patch")
        sys.exit(1)

    current_version, current_version_code = get_current_version()
    new_version = bump_version(current_version, bump_type)
    new_version_code = current_version_code + 1

    print(f"Current version: {current_version} (code: {current_version_code})")
    print(f"New version: {new_version} (code: {new_version_code})")

    # Update files
    update_package_json(new_version)
    update_build_gradle(new_version, new_version_code)
    print("✅ Updated version files")

    # Generate changelog
    changelog = generate_changelog(new_version)
    print(f"\n📝 Changelog:\n{changelog}")

    # Git commit and tag
    git_commit_and_tag(new_version, new_version_code)
    print(f"✅ Committed and tagged v{new_version}")

    print(f"\n🚀 Ready to push: git push origin master --tags")

if __name__ == "__main__":
    main()